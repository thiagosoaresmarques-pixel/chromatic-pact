export function getCartographicPathsForScope(
  scope: VaeloriaMapScope,
  zoom: number,
  layers: AtlasLayerVisibility
): CartographicPathFeature[] {
  const effectiveLod: 1 | 2 | 3 = zoom >= 2.05 ? 3 : zoom >= 1.35 ? 2 : 1;
  return VAELORIA_CARTOGRAPHIC_PATHS.filter((p) => {
    if (p.scope !== scope) return false;
    if (p.minLod > effectiveLod && scope === 'world') return false;
    if (p.kind === 'ley_conduit') return layers.leyLines;
    return layers.hydrographyAndRoutes;
  });
}

export function getCartographicToponymsForScope(
  scope: VaeloriaMapScope,
  zoom: number,
  layers: AtlasLayerVisibility
): CartographicToponymFeature[] {
  if (!layers.reliefAndToponyms) return [];
  const isCapital = scope.startsWith('capital_');
  const maxLod: 1 | 2 | 3 | 4 = isCapital
    ? 4
    : zoom >= 2.85
      ? 4
      : zoom >= 2.05
        ? 3
        : zoom >= 1.35
          ? 2
          : 1;
  return VAELORIA_CARTOGRAPHIC_TOPONYMS.filter(
    (t) => t.scope === scope && t.lod <= maxLod
  );
}

export function getHistoricalBattlefieldsForScope(
  scope: VaeloriaMapScope,
  eraFilter: VaeloriaHistoricalEraId
): Array<HistoricalBattlefieldSite & { displayX: number; displayY: number }> {
  return VAELORIA_HISTORICAL_BATTLEFIELDS.filter((site) => {
    if (eraFilter !== 'all_eras' && site.eraId !== eraFilter) return false;
    if (scope === 'world') return true;
    return site.regionalScope === scope;
  }).map((site) => ({
    ...site,
    displayX: scope === 'world' ? site.worldX : site.regionalX,
    displayY: scope === 'world' ? site.worldY : site.regionalY,
  }));
}
