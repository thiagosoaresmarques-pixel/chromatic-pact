/**
 * Converte uma polilinha em coordenadas percentuais (0..100) numa curva SVG quadrática suave
 * compatível com qualquer viewBox 16:9 (ex.: 1600x900 no Overworld ou 3200x1800 na Conquista).
 */
export function pointsToSmoothSvgPath(
  points: Array<[number, number]>,
  viewBoxWidth: number,
  viewBoxHeight: number
): string {
  if (points.length === 0) return '';
  const scaled = points.map(([px, py]) => [
    Number(((px / 100) * viewBoxWidth).toFixed(1)),
    Number(((py / 100) * viewBoxHeight).toFixed(1)),
  ]);
  if (scaled.length === 1) {
    return `M ${scaled[0][0]} ${scaled[0][1]}`;
  }
  if (scaled.length === 2) {
    return `M ${scaled[0][0]} ${scaled[0][1]} L ${scaled[1][0]} ${scaled[1][1]}`;
  }
  let d = `M ${scaled[0][0]} ${scaled[0][1]}`;
  for (let i = 1; i < scaled.length - 1; i++) {
    const [cx, cy] = scaled[i];
    const [nx, ny] = scaled[i + 1];
    const mx = Number(((cx + nx) / 2).toFixed(1));
    const my = Number(((cy + ny) / 2).toFixed(1));
    d += ` Q ${cx} ${cy} ${mx} ${my}`;
  }
  const last = scaled[scaled.length - 1];
  const prev = scaled[scaled.length - 2];
  d += ` Q ${prev[0]} ${prev[1]} ${last[0]} ${last[1]}`;
  return d;
}

